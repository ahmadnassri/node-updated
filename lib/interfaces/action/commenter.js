import { Octokit } from '@actions/github'
import * as github from '@actions/github'

/**
 * PR Commenter for GitHub Actions
 * Formats and posts dependency check reports as PR comments
 */
export default class Commenter {
  constructor (token) {
    this.octokit = new Octokit({ auth: token })
    this.context = github.context
  }

  /**
   * Format result data as markdown comment
   * @param {Array} data - Result data from engine
   * @param {Object} summary - Summary statistics
   * @returns {String} Formatted markdown comment
   */
  formatComment (data, summary) {
    let comment = '## 📦 Dependency Check Report\n\n'

    // Summary
    const totalOutdated = data.filter(item => item.status === 'outdated').length
    const totalDeprecated = data.filter(item => item.status === 'deprecated').length
    const totalUpdated = data.filter(item => item.status === 'updated').length

    if (totalOutdated === 0 && totalDeprecated === 0) {
      comment += '✅ **All dependencies are up to date!**\n\n'
      return comment
    }

    comment += `Found **${totalOutdated}** outdated and **${totalDeprecated}** deprecated dependencies.\n\n`

    // Group by ecosystem
    const npmItems = data.filter(item => item.ecosystem === 'npm')
    const dockerItems = data.filter(item => item.ecosystem === 'docker')

    // NPM section
    if (npmItems.length > 0) {
      comment += '### npm Packages\n\n'

      const outdated = npmItems.filter(item => item.status === 'outdated')
      const deprecated = npmItems.filter(item => item.status === 'deprecated')
      const updated = npmItems.filter(item => item.status === 'updated')

      if (outdated.length > 0) {
        comment += '#### Outdated\n\n'
        comment += '| Package | Current | Latest | Type | Workspace |\n'
        comment += '|---------|---------|--------|------|----------|\n'
        for (const item of outdated) {
          const workspace = item.workspace || 'root'
          comment += `| ${item.name} | \`${item.current}\` | \`${item.latest}\` | ${item.type} | ${workspace} |\n`
        }
        comment += '\n'
      }

      if (deprecated.length > 0) {
        comment += '#### Deprecated\n\n'
        comment += '| Package | Current | Type | Workspace |\n'
        comment += '|---------|---------|------|----------|\n'
        for (const item of deprecated) {
          const workspace = item.workspace || 'root'
          comment += `| ⚠️ ${item.name} | \`${item.current}\` | ${item.type} | ${workspace} |\n`
        }
        comment += '\n'
      }

      if (updated.length > 0) {
        comment += '#### ✅ Up to Date\n\n'
        comment += `${updated.length} package(s) already updated.\n\n`
      }
    }

    // Docker section
    if (dockerItems.length > 0) {
      comment += '### 🐋 Docker Images\n\n'

      const outdated = dockerItems.filter(item => item.status === 'outdated')
      const updated = dockerItems.filter(item => item.status === 'updated')

      if (outdated.length > 0) {
        comment += '#### Outdated\n\n'
        comment += '| Service | Image | Current | Latest | File |\n'
        comment += '|---------|-------|---------|--------|------|\n'
        for (const item of outdated) {
          comment += `| ${item.service} | ${item.image} | \`${item.current}\` | \`${item.latest}\` | ${item.file} |\n`
        }
        comment += '\n'
      }

      if (updated.length > 0) {
        comment += '#### ✅ Up to Date\n\n'
        comment += `${updated.length} image(s) already updated.\n\n`
      }
    }

    // Footer
    comment += '---\n'
    comment += '🤖 Generated by [Updated](https://github.com/ahmadnassri/node-updated)\n'

    if (summary.updated) {
      comment += '\n✅ Files have been updated automatically.\n'
    }

    return comment
  }

  /**
   * Post comment to current PR
   * @param {String} body - Comment body (markdown)
   * @returns {Promise<Object>} Comment creation result
   */
  async postComment (body) {
    const { owner, repo } = this.context.repo

    // Check if we're in a PR context
    if (!this.context.payload.pull_request) {
      throw new Error('Not in a pull request context. Comments can only be posted on PRs.')
    }

    const prNumber = this.context.payload.pull_request.number

    try {
      const { data: comment } = await this.octokit.rest.issues.createComment({
        owner,
        repo,
        issue_number: prNumber,
        body
      })

      return {
        success: true,
        id: comment.id,
        url: comment.html_url
      }
    } catch (error) {
      throw new Error(`Failed to post comment: ${error.message}`)
    }
  }

  /**
   * Update existing comment or create new one
   * Searches for existing Updated bot comment and updates it
   * @param {String} body - Comment body (markdown)
   * @returns {Promise<Object>} Comment result
   */
  async upsertComment (body) {
    const { owner, repo } = this.context.repo

    if (!this.context.payload.pull_request) {
      throw new Error('Not in a pull request context')
    }

    const prNumber = this.context.payload.pull_request.number

    try {
      // Find existing comment from Updated bot
      const { data: comments } = await this.octokit.rest.issues.listComments({
        owner,
        repo,
        issue_number: prNumber
      })

      const botComment = comments.find(comment =>
        comment.body?.includes('🤖 Generated by [Updated]')
      )

      if (botComment) {
        // Update existing comment
        const { data: updated } = await this.octokit.rest.issues.updateComment({
          owner,
          repo,
          comment_id: botComment.id,
          body
        })

        return {
          success: true,
          updated: true,
          id: updated.id,
          url: updated.html_url
        }
      } else {
        // Create new comment
        return await this.postComment(body)
      }
    } catch (error) {
      throw new Error(`Failed to upsert comment: ${error.message}`)
    }
  }

  /**
   * Complete workflow: format and post comment
   * @param {Array} resultData - Result data from engine
   * @param {Object} summary - Summary statistics
   * @param {Boolean} update - Whether to update existing comment
   * @returns {Promise<Object>} Complete workflow result
   */
  async addReportComment (resultData, summary, update = true) {
    try {
      const body = this.formatComment(resultData, summary)

      const result = update
        ? await this.upsertComment(body)
        : await this.postComment(body)

      return result
    } catch (error) {
      throw new Error(`Comment workflow failed: ${error.message}`)
    }
  }
}
